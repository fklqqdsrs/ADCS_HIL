/* USER CODE BEGIN EV */
void print_hardfault_info(hard_fault_stack_t *stack)
{
	printf("\r\n[HardFault Handler]\r\n");
    printf("R0  = 0x%08lX\r\n", stack->r0);
    printf("R1  = 0x%08lX\r\n", stack->r1);
    printf("R2  = 0x%08lX\r\n", stack->r2);
    printf("R3  = 0x%08lX\r\n", stack->r3);
    printf("R12 = 0x%08lX\r\n", stack->r12);
    printf("LR  = 0x%08lX\r\n", stack->lr);
    printf("PC  = 0x%08lX\r\n", stack->pc);
    printf("xPSR= 0x%08lX\r\n", stack->psr);

    printf("\r\nSystem Fault Status:\r\n");
    printf("CFSR = 0x%08lX\r\n", SCB->CFSR);
    printf("HFSR = 0x%08lX\r\n", SCB->HFSR);
    printf("DFSR = 0x%08lX\r\n", SCB->DFSR);
    printf("AFSR = 0x%08lX\r\n", SCB->AFSR);
    printf("MMFAR = 0x%08lX\r\n", SCB->MMFAR);
    printf("BFAR  = 0x%08lX\r\n", SCB->BFAR);

#if (configUSE_TRACE_FACILITY == 1 && configUSE_STATS_FORMATTING_FUNCTIONS == 1)
    printf("\r\n[FreeRTOS Task List]\r\n");
    char taskList[512];
    vTaskList(taskList);
    printf("%s\r\n", taskList);
#endif

    TaskHandle_t current = xTaskGetCurrentTaskHandle();
    if (current != NULL)
    {
        printf("Current task: %s\r\n", pcTaskGetName(current));
    }

    printf("\r\n!!! SYSTEM HALTED !!!\r\n");
    while (1);
}
